// Package config 解析、迁移与持久化 router-config.json。
//
// 讲清**为什么**这一层刻意保留了一些看起来可以简化的行为，以及工作空间的边界在
// 哪里。改了这里的约定之前，请先读完。
//
// # 兼容性契约
//
// 参照实现（Python）已退役，它的行为由 testdata 语料逐字节锁住，那是本项目唯一的
// 兼容性凭证。因此本包的目标是「字节级可用」而不是「设计得干净」：
//
//   - 字段顺序按插入顺序落盘（不排序），避免每次保存都重排整份文件；
//   - 整数与浮点分别渲染（60 与 60.0），与 canonical 包一致；
//   - 错误文本原样上报给管理 API 的调用方，属于对外契约，措辞不得改写；
//   - 迁移保留 v1/v2 的列表布局与 v3 的 pool 白名单语义，包括其中已知的怪异之处。
//
// 语料没有覆盖到的输入**不做猜测式对齐**：要么失败关闭（InternalError），要么按
// 调用方给出的顺序取确定性的结果。宁可显式分叉，也不产出一份「碰巧对得上」的配置。
//
// # 顶层 upstream_routes 为什么被忽略
//
// 只由 providers[].routes 汇总而来。配置文件顶层的 upstream_routes 与 provider
// key 级的 upstream_routes 都会被忽略——这是参照实现的实际行为（config.py:877 从
// 空字典起步，而 KeyConfig 在 config.py:963 构造时未传 upstream_routes）。迁移
// 对拍语料已固化该行为，不是遗漏。
//
// # 工作空间
//
// 工作空间（workspaces）是 Go 侧新增的能力，参照实现没有，因此这一部分**没有**
// 语料可对，它的兼容性契约是另一条：**不影响既有配置与既有调用方**。
//
//	config_version 仍是 4，workspaces 是可选新增字段，
//	顶层 tasks 就是 DefaultWorkspace。
//
// 由此推出几条必须保持的性质：
//
//   - 不带 X-AMKR-Workspace 头的请求行为逐字节不变。正因如此，被语料锁定的响应体
//     （如 tasks/list）**没有、也不允许**新增 workspace 字段——当前空间由请求头决定，
//     不体现在响应里。
//   - 工作空间**只隔离任务**。模型 ID、别名、隐藏别名与 unified-model 仍然全局唯一，
//     任务名也不能与它们撞名（见 Validate）：否则 resolve_route 的语义会取决于查表
//     顺序，而那是全局唯一的判断，工作空间不能用来遮蔽模型名。
//   - 任务名只在同一工作空间内唯一。两个空间各有一个 summarize 是合法配置。
//   - 工作空间由「在它里面建任务」隐式产生，没有独立的创建入口，配置里的空分组也会
//     被清掉（configops.writeWorkspaceTasks 删空即删分组）。WorkspaceNames 因此由
//     任务反推而不是回放配置键：一个没有成员的分组既不可观测也没有意义，两边口径
//     必须相同，否则界面上会出现一个删不掉的幽灵分组。
//   - 未配置的工作空间名**不是错误**。那里没有任务，于是按普通模型名继续解析，最终
//     和「模型未配置」是同一个 404。单加一条「空间不存在」的错误既没有信息量，也会
//     多一种需要维护的状态。NormalizeWorkspace 只做去空白，不校验存在性。
//   - 手工构造 RouterConfig 的调用方（测试、内部装配）可以不管工作空间：Validate
//     会把零值 Workspace 归一成 DefaultWorkspace。
//
// 需要「工作空间在配置里长什么样」的读者，请看 docs/USAGE.md 9.1；需要「调用方怎么
// 选空间」的，看 docs/API.md 的「任务路由 → 工作空间」。
//
// # 校验的顺序也是契约
//
// Validate 的错误顺序与措辞对齐 config.py:1108，语料逐条断言。新增检查时请追加在
// **末尾**或紧邻同类检查，不要插到既有检查之前——那会改变既有非法配置报出的第一条
// 错误，从而让语料失效。
